import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';
import 'dart:ui' as ui;

import 'package:crypto/crypto.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';

import '../models/drive_entry.dart';
import '../models/song_details.dart';
import 'audio_tags.dart';
import 'baidu_client.dart';
import 'offline_library.dart';

class SongDetailsRepository extends ChangeNotifier {
  SongDetailsRepository(this.directory, this.client, {this.library});
  final Directory directory;
  final BaiduClient client;
  final OfflineLibrary? library;
  final Map<String, SongDetails> _cache = {};
  final Map<String, Future<SongDetails>> _pending = {};
  bool Function(String)? canRead;
  int _generation = 0;

  String key(DriveEntry entry) => sha256
      .convert(utf8.encode('${entry.demo}:${entry.id}:${entry.path}'))
      .toString();
  SongDetails cached(DriveEntry entry) =>
      _cache[key(entry)] ?? const SongDetails();

  Future<void> initialize() async {
    await directory.create(recursive: true);
    await for (final file in directory.list(followLinks: false)) {
      if (file is! File ||
          !RegExp(r'[/\\][a-f0-9]{64}\.json$').hasMatch(file.path)) {
        continue;
      }
      try {
        if (await file.length() > AudioTags.maxLyrics * 2) continue;
        final value = Map<String, dynamic>.from(
          jsonDecode(await file.readAsString()) as Map,
        );
        final cover = value['coverPath'] as String?;
        // Cached paths are filenames generated by this repository, never remote paths.
        value['coverPath'] =
            cover != null &&
                RegExp(r'^[a-f0-9]{64}\.image$').hasMatch(cover) &&
                await File('${directory.path}/$cover').exists()
            ? '${directory.path}/$cover'
            : null;
        final name = file.uri.pathSegments.last;
        _cache[name.substring(0, 64)] = SongDetails.fromJson(value);
      } catch (_) {
        /* Ignore corrupt cached metadata. */
      }
    }
  }

  Future<SongDetails> load(DriveEntry entry, {bool refresh = false}) {
    final id = key(entry);
    if (_pending[id] != null) return _pending[id]!;
    if (!refresh && _cache.containsKey(id)) return Future.value(cached(entry));
    final future = _load(entry).whenComplete(() {
      _pending.remove(id);
    });
    _pending[id] = future;
    return future;
  }

  Future<SongDetails> _load(DriveEntry entry) async {
    final generation = _generation;
    var result = cached(entry);
    if (entry.demo) {
      final cover = await rootBundle.load('assets/artwork/demo.png');
      result = result.copyWith(
        lyrics:
            '[00:00.00]云间 · 原创旋律\n[00:08.00]此曲为器乐，没有演唱歌词\n[00:16.00]这里演示时间轴与逐行高亮\n[00:24.00]点击任意一行可跳转播放',
        lyricsSource: '原创试听说明 · 非演唱歌词',
        coverPath:
            result.coverPath ??
            await _writeCover(entry, cover.buffer.asUint8List()),
        coverSource: '云间原创示例封面',
      );
      await _save(entry, result);
      return result;
    }
    final local = library?.localPath(entry);
    try {
      Uint8List header;
      if (local != null) {
        header = await readLimited(
          File(local).openRead(0, AudioTags.maxHeader),
          AudioTags.maxHeader,
          truncate: true,
        );
      } else if (canRead?.call(entry.path) == true &&
          client.session.connected) {
        final response = await client.openStream(
          entry,
          start: 0,
          end: AudioTags.maxHeader,
        );
        header = await readLimited(
          response.stream,
          AudioTags.maxHeader,
          truncate: true,
        );
      } else {
        return result;
      }
      final tags = AudioTags.parse(header);
      if (generation != _generation) return cached(entry);
      result = result.copyWith(
        title: tags.title,
        artist: tags.artist,
        album: tags.album,
        lyrics: result.lyrics ?? tags.lyrics,
        lyricsSource:
            result.lyricsSource ?? (tags.lyrics == null ? null : '音乐内嵌标签'),
      );
      if (result.coverPath == null && tags.cover != null) {
        result = result.copyWith(
          coverPath: await _writeCover(entry, tags.cover!),
          coverSource: '音乐内嵌封面',
        );
      }
    } catch (_) {
      /* Tags are optional, try sidecars even if header reading failed. */
    }
    if (canRead?.call(entry.path) == true &&
        client.session.connected &&
        generation == _generation) {
      try {
        final siblings = <DriveEntry>[];
        int? start = 0;
        // Bounded pages in this song's parent only; never recurse or list /.
        for (var page = 0; page < 10 && start != null; page++) {
          if (generation != _generation || canRead?.call(entry.path) != true) {
            break;
          }
          final response = await client.listDirectory(
            entry.parent,
            start: start,
          );
          siblings.addAll(
            response.entries.where(
              (e) => e.parent == entry.parent && !e.isDirectory,
            ),
          );
          start = response.nextStart;
        }
        DriveEntry? named(List<String> names) {
          for (final name in names) {
            for (final file in siblings) {
              if (file.name.toLowerCase() == name.toLowerCase()) return file;
            }
          }
          return null;
        }

        final lrc = named(['${entry.title}.lrc']);
        if (lrc != null &&
            result.lyricsSource != '手机导入' &&
            !(result.lyricsSource?.startsWith('LRCLIB') ?? false)) {
          try {
            final text = AudioTags.decodeText(
              await _readSidecar(lrc, AudioTags.maxLyrics),
            );
            if (text.isNotEmpty) {
              result = result.copyWith(
                lyrics: text,
                lyricsSource: '同目录 ${lrc.name}',
              );
            }
          } catch (_) {
            /* Keep embedded/cached lyrics if the sidecar is unavailable. */
          }
        }
        if (result.coverPath == null) {
          final picture = named([
            for (final stem in [entry.title, 'cover', 'folder', 'front'])
              for (final ext in ['jpg', 'jpeg', 'png', 'webp']) '$stem.$ext',
          ]);
          if (picture != null) {
            final bytes = await _readSidecar(picture, AudioTags.maxCover);
            result = result.copyWith(
              coverPath: await _writeCover(entry, bytes),
              coverSource: '同目录 ${picture.name}',
            );
          }
        }
      } catch (_) {
        /* Sidecar failures must never interrupt the audio stream. */
      }
    }
    if (generation != _generation) return cached(entry);
    // Do not overwrite an import/selection completed while a scan was running.
    final latest = cached(entry);
    if (latest.lyricsSource == '手机导入' ||
        (latest.lyricsSource?.startsWith('LRCLIB') ?? false)) {
      result = result.copyWith(
        lyrics: latest.lyrics,
        lyricsSource: latest.lyricsSource,
      );
    }
    if (latest.coverPath != null) {
      result = result.copyWith(
        coverPath: latest.coverPath,
        coverSource: latest.coverSource,
      );
    }
    await _save(entry, result);
    return result;
  }

  Future<Uint8List> _readSidecar(DriveEntry entry, int maximum) async {
    if (entry.size > maximum || canRead?.call(entry.path) != true) {
      throw const FormatException('Invalid sidecar');
    }
    final response = await client.openStream(entry);
    return readLimited(response.stream, maximum);
  }

  static Future<Uint8List> readLimited(
    Stream<List<int>> stream,
    int maximum, {
    bool truncate = false,
  }) async {
    final bytes = BytesBuilder(copy: false);
    await for (final chunk in stream.timeout(const Duration(seconds: 20))) {
      final remaining = maximum - bytes.length;
      if (chunk.length > remaining) {
        if (!truncate) throw const FormatException('文件过大');
        bytes.add(chunk.sublist(0, remaining));
        break;
      }
      bytes.add(chunk);
      if (truncate && bytes.length == maximum) break;
    }
    return bytes.takeBytes();
  }

  Future<String> _writeCover(DriveEntry entry, Uint8List bytes) async {
    if (bytes.isEmpty || bytes.length > AudioTags.maxCover) {
      throw const FormatException('请选择不超过 5 MB 的图片');
    }
    final codec = await ui.instantiateImageCodec(
      bytes,
      targetWidth: 512,
      targetHeight: 512,
      allowUpscaling: false,
    );
    final frame = await codec.getNextFrame();
    // Store a bounded decoded image rather than an oversized or animated original.
    final encoded = await frame.image.toByteData(
      format: ui.ImageByteFormat.png,
    );
    frame.image.dispose();
    codec.dispose();
    if (encoded == null) throw const FormatException('图片无法解码');
    final hash = sha256.convert(encoded.buffer.asUint8List()).toString();
    final file = File('${directory.path}/$hash.image');
    await file.writeAsBytes(encoded.buffer.asUint8List(), flush: true);
    return file.path;
  }

  Future<void> setLyrics(DriveEntry entry, String text, String source) async {
    if (utf8.encode(text).length > AudioTags.maxLyrics) {
      throw const FormatException('歌词不能超过 256 KB');
    }
    await _save(
      entry,
      cached(entry).copyWith(lyrics: text, lyricsSource: source),
    );
  }

  Future<void> setCover(
    DriveEntry entry,
    Uint8List bytes,
    String source,
  ) async {
    final path = await _writeCover(entry, bytes);
    await _save(
      entry,
      cached(entry).copyWith(coverPath: path, coverSource: source),
    );
  }

  Future<void> _save(DriveEntry entry, SongDetails details) async {
    final data = details.toJson();
    data['coverPath'] = details.coverPath == null
        ? null
        : File(details.coverPath!).uri.pathSegments.last;
    await File(
      '${directory.path}/${key(entry)}.json',
    ).writeAsString(jsonEncode(data), flush: true);
    _cache[key(entry)] = details;
    notifyListeners();
  }

  void invalidatePending() {
    _generation++;
  }

  Future<void> move(DriveEntry old, DriveEntry replacement) async {
    invalidatePending();
    if (_cache.containsKey(key(old))) await _save(replacement, cached(old));
  }
}
